-- Rokomari Inventory schema and security setup
-- Run in Supabase Dashboard > SQL Editor using the project owner account.
-- Review before running on a project containing important data.
create extension if not exists pgcrypto;

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'employee' check (role in ('admin','employee')),
  created_at timestamptz not null default now()
);
alter table public.user_roles enable row level security;
revoke all on public.user_roles from anon, authenticated;
grant select on public.user_roles to authenticated;
drop policy if exists users_read_own_role on public.user_roles;
create policy users_read_own_role on public.user_roles
for select to authenticated using (user_id = (select auth.uid()));

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text unique,
  quantity integer not null default 0 check (quantity >= 0),
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant select on public.products to authenticated;
drop policy if exists products_read_authenticated on public.products;
create policy products_read_authenticated on public.products
for select to authenticated using (true);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  quantity integer not null check (quantity > 0),
  customer_phone text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
alter table public.sales add column if not exists customer_phone text;
alter table public.sales add column if not exists created_by uuid default auth.uid();
alter table public.sales enable row level security;
revoke all on public.sales from anon, authenticated;
grant select on public.sales to authenticated;
drop policy if exists sales_read_admin_only on public.sales;
create policy sales_read_admin_only on public.sales
for select to authenticated using ((select public.is_admin()));

create table if not exists public.product_financials (
  product_id bigint primary key references public.products(id) on delete cascade,
  buy_price numeric(12,2) not null default 0 check (buy_price >= 0),
  sell_price numeric(12,2) not null default 0 check (sell_price >= 0),
  updated_at timestamptz not null default now()
);
alter table public.product_financials enable row level security;
revoke all on public.product_financials from anon, authenticated;
grant select on public.product_financials to authenticated;
drop policy if exists financials_admin_read on public.product_financials;
create policy financials_admin_read on public.product_financials
for select to authenticated using ((select public.is_admin()));

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  note text not null,
  amount numeric(12,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
alter table public.expenses enable row level security;
revoke all on public.expenses from anon, authenticated;
grant select on public.expenses to authenticated;
drop policy if exists expenses_admin_read on public.expenses;
create policy expenses_admin_read on public.expenses
for select to authenticated using ((select public.is_admin()));

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
 select exists (select 1 from public.user_roles
 where user_id = (select auth.uid()) and role = 'admin');
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- Only authenticated users can create ordinary products via this controlled function.
create or replace function public.create_product(p_name text, p_sku text, p_quantity integer)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare new_id bigint;
begin
 if (select auth.uid()) is null then raise exception 'Login required'; end if;
 if p_name is null or length(trim(p_name)) = 0 then raise exception 'Product name required'; end if;
 if p_quantity is null or p_quantity < 0 then raise exception 'Quantity cannot be negative'; end if;
 insert into public.products(name,sku,quantity)
 values(trim(p_name),nullif(trim(p_sku),''),p_quantity) returning id into new_id;
 return new_id;
end; $$;
revoke all on function public.create_product(text,text,integer) from public, anon;
grant execute on function public.create_product(text,text,integer) to authenticated;

-- Controlled sale transaction: deduct stock and create sale row atomically.
create or replace function public.record_sale(p_product_id bigint, p_quantity integer, p_customer_phone text default null)
returns void language plpgsql security definer set search_path = ''
as $$
begin
 if (select auth.uid()) is null then raise exception 'Login required'; end if;
 if p_quantity is null or p_quantity <= 0 then raise exception 'Quantity must be greater than zero'; end if;
 update public.products set quantity = quantity - p_quantity
 where id = p_product_id and quantity >= p_quantity;
 if not found then raise exception 'Product not found or insufficient stock'; end if;
 insert into public.sales(product_id,quantity,customer_phone,created_by)
 values(p_product_id,p_quantity,nullif(trim(p_customer_phone),' '),(select auth.uid()));
end; $$;
revoke all on function public.record_sale(bigint,integer,text) from public, anon;
grant execute on function public.record_sale(bigint,integer,text) to authenticated;

create or replace function public.upsert_product_financials(p_product_id bigint,p_buy_price numeric,p_sell_price numeric)
returns void language plpgsql security definer set search_path = ''
as $$
begin
 if not public.is_admin() then raise exception 'Admin only'; end if;
 if p_buy_price < 0 or p_sell_price < 0 then raise exception 'Price cannot be negative'; end if;
 insert into public.product_financials(product_id,buy_price,sell_price,updated_at)
 values(p_product_id,p_buy_price,p_sell_price,now())
 on conflict(product_id) do update set buy_price=excluded.buy_price,sell_price=excluded.sell_price,updated_at=now();
end; $$;
revoke all on function public.upsert_product_financials(bigint,numeric,numeric) from public, anon;
grant execute on function public.upsert_product_financials(bigint,numeric,numeric) to authenticated;

create or replace function public.add_expense(p_note text,p_amount numeric)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare new_id bigint;
begin
 if not public.is_admin() then raise exception 'Admin only'; end if;
 if p_note is null or length(trim(p_note))=0 or p_amount is null or p_amount<=0 then raise exception 'Valid note and positive amount required'; end if;
 insert into public.expenses(note,amount,created_by) values(trim(p_note),p_amount,(select auth.uid())) returning id into new_id;
 return new_id;
end; $$;
revoke all on function public.add_expense(text,numeric) from public, anon;
grant execute on function public.add_expense(text,numeric) to authenticated;

